#!/usr/bin/env node
/**
 * Wire the version-controlled .husky/ hooks into this repo's real hooks dir.
 *
 * WHY THIS IS NODE AND NOT THE OLD BASH SCRIPT
 * git reads hooks from `.git/hooks`, never from `.husky/`, so every hook in
 * `.husky/` is inert until something writes a delegator. That something used to
 * be `scripts/install-git-hooks.sh`, a manual "run once after cloning" step that
 * appears in no README, no CONTRIBUTING, and no npm script. Measured 2026-09-01
 * on the main ZAOOS clone: `.git/hooks` contained only `*.sample` files, so the
 * pre-commit secret scan and the PII scan had never run on a single commit.
 *
 * This runs from `prepare`, which npm executes on every `npm install` and
 * `npm ci`, so a fresh clone gets the gates without anyone remembering a step.
 * Node rather than bash because npm on Windows shells out to cmd.exe, and a
 * `bash` that is not on PATH would fail the whole install.
 *
 * IT CAN NEVER FAIL AN INSTALL. Every path exits 0. A build box with no git
 * (Vercel, a tarball, a Docker layer) gets a loud warning and a working install
 * rather than a broken one - the hooks are a local developer gate, and taking
 * production builds down to enforce one would be the worse trade.
 */
import { execFileSync } from 'node:child_process';
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const MARKER = '# zaoos-husky-delegator';
const HOOKS = ['pre-commit'];

const warn = (msg) => console.warn(`[git-hooks] ${msg}`);

function git(args) {
  return execFileSync('git', args, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

/**
 * Wiring a hook that cannot run turns "the gate never fired" into "nobody can
 * commit", which is the worse failure. So each hook declares what it needs and
 * we check it by RUNNING the thing, never by asking PATH whether it exists.
 *
 * The one that matters today: `.husky/pre-commit` invokes the PII scan as a
 * bare `python3 ... || exit 1`. On the Windows desktop `python3` is the
 * Microsoft Store App Execution Alias - present on PATH, so `command -v
 * python3` says yes, and executing it prints "Python was not found" and exits
 * 49. Measured 2026-09-01 on that box: python3 -> 49, python -> 0, py -> 0.
 * Auto-wiring there would block every commit, so we refuse and say exactly why.
 */
const PREREQS = {
  'pre-commit': () => {
    try {
      execFileSync('python3', ['-c', 'import sys; sys.exit(0 if sys.version_info[0] == 3 else 1)'], {
        stdio: 'ignore',
      });
      return null;
    } catch {
      return [
        '`python3` does not run a working Python 3 here, and .husky/pre-commit',
        'calls it directly for the PII scan - wiring the hook would block every',
        'commit on this machine. On Windows `python3` is usually the Microsoft',
        'Store alias stub while `python` is the real interpreter. Fix the alias',
        '(Settings > Apps > Advanced app settings > App execution aliases) or',
        'install Python 3 as python3, then re-run: node scripts/install-git-hooks.mjs',
      ].join(' ');
    }
  },
};

/**
 * The delegator resolves .husky/ at RUN time rather than baking in an absolute
 * path. A worktree shares the main clone's hooks dir (verified: `git rev-parse
 * --git-path hooks` in a worktree returns the parent repo's), so a baked path
 * would point every worktree's commits at whichever checkout happened to run
 * the installer.
 *
 * Missing hook is a FAIL, not a skip: a gate that vanishes should say so rather
 * than let the commit through quietly (silent-failure-guard rule 3).
 */
function delegator(hook) {
  return `#!/usr/bin/env sh
${MARKER} - generated by scripts/install-git-hooks.mjs, do not edit
hook="$(git rev-parse --show-toplevel)/.husky/${hook}"
if [ ! -f "$hook" ]; then
  echo "[git-hooks] missing $hook - the ${hook} gates did NOT run." >&2
  echo "[git-hooks] restore it, or bypass deliberately: git commit --no-verify" >&2
  exit 1
fi
exec sh "$hook" "$@"
`;
}

try {
  const top = git(['rev-parse', '--show-toplevel']);
  // `--git-path` returns a path relative to the CWD in a plain clone and an
  // absolute one in a worktree. resolve() handles both.
  const hooksDir = resolve(process.cwd(), git(['rev-parse', '--git-path', 'hooks']));
  mkdirSync(hooksDir, { recursive: true });

  let wired = 0;
  for (const hook of HOOKS) {
    const src = join(top, '.husky', hook);
    if (!existsSync(src)) continue;

    const blocked = PREREQS[hook]?.();
    if (blocked) {
      warn(`NOT wiring ${hook}: ${blocked}`);
      warn(`until then the ${hook} secret + PII scans do not run on this machine.`);
      continue;
    }

    const dst = join(hooksDir, hook);
    if (existsSync(dst) && !readFileSync(dst, 'utf8').includes(MARKER)) {
      const backup = `${dst}.bak.${Date.now()}`;
      copyFileSync(dst, backup);
      warn(`backed up your existing ${hook} -> ${backup}`);
    }

    writeFileSync(dst, delegator(hook), { mode: 0o755 });
    chmodSync(dst, 0o755);
    wired += 1;
  }

  if (wired > 0) warn(`wired ${wired} hook(s) from .husky/ into ${hooksDir}`);
} catch (err) {
  warn(`could not install hooks: ${err instanceof Error ? err.message : String(err)}`);
  warn('the pre-commit secret + PII scans will NOT run here.');
  warn('from a git clone, enable them with: node scripts/install-git-hooks.mjs');
}
